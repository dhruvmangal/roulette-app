import ajv from '~/libs/ajv'
import ServiceBase from '~/services/serviceBase'
import { ApplyWalletTransactionService } from '~/services/wallet'
import RouletteEmitter from '~/socket-resources/emitters/roulette.emitter'
import { recordAudit } from '~/utils/admin.utils'
import { ADMIN_ACTIONS, ADMIN_TARGETS } from '~/utils/constants/admin.constants'
import { SUCCESS_MSG } from '~/utils/constants/success'
import { WALLET_DIRECTIONS, WALLET_REFERENCE_TYPES, WALLET_TRANSACTION_TYPES } from '~/utils/constants/wallet.constants'
import { inTransaction, withTransaction } from '~/utils/transaction.utils'

const constraints = ajv.compile({
  type: 'object',
  properties: {
    playerId: { type: 'integer', minimum: 1 },
    direction: { enum: Object.values(WALLET_DIRECTIONS) },
    amount: { type: 'integer', minimum: 1, maximum: 1e9 },
    reason: { type: 'string', minLength: 3, maxLength: 500 },
    // Generated by the admin app per form, so a double-submit moves chips once.
    requestId: { type: 'string', minLength: 8, maxLength: 64 }
  },
  required: ['playerId', 'direction', 'amount', 'reason', 'requestId']
})

/**
 * Credits or debits a player's chips by hand, as an ADMIN_ADJUST ledger row
 * that names the admin and the reason. A debit can never take a balance
 * below zero.
 */
export class AdjustWalletService extends ServiceBase {
  get constraints () {
    return constraints
  }

  async run () {
    const { playerId, direction, amount, reason, requestId } = this.args
    const { admin } = this.context

    const result = await withTransaction(this, async (transaction) => {
      const applied = await ApplyWalletTransactionService.execute({
        playerId,
        amount,
        direction,
        type: WALLET_TRANSACTION_TYPES.ADMIN_ADJUST,
        referenceType: WALLET_REFERENCE_TYPES.ADMIN,
        referenceId: String(admin.adminUserId),
        idempotencyKey: `admin:${requestId}`,
        metadata: { reason, adminUserId: admin.adminUserId, adminEmail: admin.email }
      }, inTransaction(this.context, transaction))
      if (!applied.successful) return this.mergeErrors(applied.errors)
      if (applied.result.replayed) return { ...applied.result, message: SUCCESS_MSG.WALLET_ADJUSTED }

      await recordAudit(this.context, transaction, {
        action: ADMIN_ACTIONS.WALLET_ADJUST,
        targetType: ADMIN_TARGETS.PLAYER,
        targetId: playerId,
        details: { direction, amount, reason, walletTransactionId: applied.result.walletTransaction.walletTransactionId }
      })
      return { ...applied.result, message: SUCCESS_MSG.WALLET_ADJUSTED }
    })

    if (result && !result.replayed) RouletteEmitter.walletUpdated(playerId, result.wallet)
    return result
  }
}
